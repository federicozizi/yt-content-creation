-- =====================================================================
-- TABLE: tax_regimes (lookup table of tax regimes)
-- =====================================================================
create table if not exists tax_regimes (
  code text primary key,
  description text not null,
  annual_revenue_limit numeric,    -- null = no limit
  substitute_rate numeric,         -- null if not applicable
  notes text
);

insert into tax_regimes (code, description, annual_revenue_limit, substitute_rate, notes) values
