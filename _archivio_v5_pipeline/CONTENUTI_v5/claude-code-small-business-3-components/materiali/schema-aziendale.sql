on conflict (code) do nothing;

-- =====================================================================
-- TABLE: clients (registry + tax regime + revenue)
-- =====================================================================
create table if not exists clients (
  id uuid primary key default gen_random_uuid(),
  company_name text not null,
  vat_number text unique,
  tax_id text,
  tax_regime_code text references tax_regimes(code),
  current_year_revenue numeric default 0,
  previous_year_revenue numeric default 0,
  acquisition_date date default current_date,
  contact_email text,
  industry text,
  active boolean default true,
  created_at timestamptz default now(),
  updated_at timestamptz default now()
);

create index if not exists idx_clients_regime on clients(tax_regime_code);
create index if not exists idx_clients_active on clients(active);

-- =====================================================================
-- TABLE: custom_deadlines (firm-specific deadlines NOT in the standard
-- national fiscal calendar)
-- =====================================================================
create table if not exists custom_deadlines (
  id uuid primary key default gen_random_uuid(),
  client_id uuid references clients(id) on delete cascade,
  type text not null,                  -- e.g. 'board_renewal', 'consulting_contract_renewal'
  description text,
  due_date date not null,
  recurrence text,                     -- 'annual', 'monthly', 'one-off'
  reminder_days_before int default 7,
  completed boolean default false,
  notes text,
  created_at timestamptz default now()
);

create index if not exists idx_deadlines_date on custom_deadlines(due_date);
create index if not exists idx_deadlines_client on custom_deadlines(client_id);
create index if not exists idx_deadlines_active on custom_deadlines(completed) where completed = false;

-- =====================================================================
-- TABLE: internal_notes (team comments on each client,
-- including alerts generated by custom agents)
-- =====================================================================
create table if not exists internal_notes (
  id uuid primary key default gen_random_uuid(),
  client_id uuid references clients(id) on delete cascade,
  type text not null,                  -- 'comment', 'threshold_alert', 'deadline_alert', 'attention_flag'
  text text not null,
  author text,                          -- firm partner name or 'agent:regime-checker'
  invoice_chaser_flag text,            -- e.g. 'do_not_chase', 'soft_chase', null
  read boolean default false,
  created_at timestamptz default now()
);

create index if not exists idx_notes_client on internal_notes(client_id);
create index if not exists idx_notes_type on internal_notes(type);
create index if not exists idx_notes_unread on internal_notes(read) where read = false;
create index if not exists idx_notes_chaser_flag on internal_notes(invoice_chaser_flag) where invoice_chaser_flag is not null;

-- =====================================================================
-- HELPFUL VIEWS (optional, for frequent queries)
-- =====================================================================

-- Clients close to their regime limit (for regime-checker)
create or replace view v_clients_near_limit as
select
  c.id,
  c.company_name,
  c.tax_regime_code,
  c.current_year_revenue,
  r.annual_revenue_limit,
  round((c.current_year_revenue / nullif(r.annual_revenue_limit, 0) * 100)::numeric, 1) as percentage_of_limit
from clients c
join tax_regimes r on r.code = c.tax_regime_code
where c.active = true
  and r.annual_revenue_limit is not null
  and c.current_year_revenue >= r.annual_revenue_limit * 0.8;

-- Custom deadlines upcoming in the next 30 days
create or replace view v_upcoming_deadlines as
select
  d.id,
  d.client_id,
  c.company_name,
  d.type,
  d.description,
  d.due_date,
  d.due_date - current_date as days_remaining
from custom_deadlines d
join clients c on c.id = d.client_id
where d.completed = false
  and d.due_date <= current_date + interval '30 days'
order by d.due_date;

